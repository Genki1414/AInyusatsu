// 全省庁統一資格で参加できる案件かどうかの判定。
// 参照：CLAUDE.md「全省庁統一資格で参加できる入札案件を収集・解析し」
//       CLAUDE.md「やらないこと：自治体・建設工事（V2）」
//
// 【なぜ必要か】
// KKJ（官公需情報ポータル）は国の機関も自治体も、物品も工事も区別せずに返す。
// 実測（2026-08-21の公告日ぶん）では1日543件が入り、その25%が建設工事だった。
// 全件をAI解析すると月100万円を超える（実測 約69円/件）。
// 対象外と決めてある案件に費用を払わないよう、解析の前に落とす。
//
// 【全省庁統一資格の範囲】
// 各府省庁と、その地方支分部局（地方整備局・国税局・労働局など）が使う共通の資格。
// 建設工事は対象外（工事は別の資格制度）。自治体は各団体が独自の資格を持つ。
// 独立行政法人・国立大学法人は、統一資格をそのまま使わない法人が多い。
//
// 【推測で「対象」にしない】
// 判定できない機関は「未判定」にして、対象にも対象外にもしない。
// 対象外へ倒すと商機を落とし、対象へ倒すと費用を払う。どちらも黙って決めない。
// 未判定の件数は必ず表に出して、人が見て決められるようにする。

export type GovScope = "国" | "自治体" | "独立行政法人等" | "不明";

/**
 * 独立行政法人など。国の機関の名前（◯◯省）を含むことがあるため最初に見る。
 * 例：「国立研究開発法人 宇宙航空研究開発機構」「国立大学法人◯◯大学」
 */
const INCORPORATED_PATTERNS: RegExp[] = [
  /独立行政法人/,
  /国立研究開発法人/,
  /国立大学法人/,
  /大学共同利用機関法人/,
  /公立大学法人/,
  /国立高等専門学校機構/,
  /国立病院機構/,
  /地域医療機能推進機構/,
  /日本年金機構/,
  /日本司法支援センター/,
  /沖縄科学技術大学院大学/,
];

/**
 * 国の機関。府省庁と、その地方支分部局。
 * 「◯◯局」のような広い語は使わない（東京都水道局のような自治体の部局と衝突するため）。
 */
const NATIONAL_PATTERNS: RegExp[] = [
  // 府省庁そのもの。略称に頼らず、庁まで含めた名前で判定する
  // （「警察」だけで見ると「◯◯県警察本部」を国と誤判定する）
  /内閣(官房|府|法制局)/,
  /(総務|法務|外務|財務|文部科学|厚生労働|農林水産|経済産業|国土交通|環境|防衛)省/,
  /(復興|デジタル|宮内|金融|消費者|警察|こども家庭)庁/,
  /(国税|特許|中小企業|資源エネルギー|観光|気象|海上保安|林野|水産|スポーツ|文化)庁/,
  /(出入国在留管理|公安調査|防衛装備|原子力規制|検察)庁/,
  /(人事院|会計検査院|公正取引委員会)/,
  /(衆議院|参議院|国立国会図書館)/,
  /(最高|高等|地方|家庭|簡易)裁判所/,
  // 地方支分部局
  /地方(整備|農政|経済産業|運輸|厚生|防衛)局/,
  /(北海道開発局|沖縄総合事務局|地方環境事務所)/,
  /(森林管理|総合通信|財務|航空|管区警察|国税|沖縄防衛)局/,
  /(税務署|労働局|労働基準監督署|公共職業安定所|ハローワーク)/,
  /(法務局|刑務所|拘置所|少年院|入国管理)/,
  /(税関|海上保安部|海上保安署|管区海上保安本部)/,
  /(気象台|航空交通管制部|地方防衛局|防衛支局)/,
  /(自衛隊|駐屯地|地方協力本部|補給処)/,
  /(検疫所|地方厚生局|財務事務所)/,
];

/**
 * 自治体。都道府県・市区町村と、その関係団体。
 * 国の機関の判定を先に行うため、ここは末尾の語で広く拾ってよい。
 */
const LOCAL_PATTERNS: RegExp[] = [
  /^(北海道|東京都)/,
  /[都道府県]\s*(教育委員会|警察本部|企業局|水道局|病院局|環境局)/,
  /[^\s]{2,}[市区町村](役所|役場|教育委員会|水道局|消防本部|病院|議会)?$/,
  /[^\s]{2,}[都道府県](庁|議会)?$/,
  /(一部事務組合|広域連合|企業団|事務組合)/,
  /(市立|町立|村立|区立|県立|都立|府立|道立)/,
];

/** 機関名から、どの区分の発注者かを判定する。判定できなければ「不明」。 */
export function classifyAgencyScope(name: string): GovScope {
  const target = name.trim();
  if (target === "") return "不明";

  // 「国立大学法人◯◯大学」のように国の語を含むため、独法系を最初に見る
  if (INCORPORATED_PATTERNS.some((pattern) => pattern.test(target))) return "独立行政法人等";
  // 「国土交通省 北海道開発局」のように自治体名を含むため、国を自治体より先に見る
  if (NATIONAL_PATTERNS.some((pattern) => pattern.test(target))) return "国";
  if (LOCAL_PATTERNS.some((pattern) => pattern.test(target))) return "自治体";
  return "不明";
}

export type ScopeVerdict = "対象" | "対象外" | "未判定";

export type ScopeInput = {
  /** 機関の区分。classifyAgencyScope の結果 */
  govScope: GovScope;
  /** KKJのCategory（物品 / 役務 / 工事 / 不明） */
  procurement: string;
};

export type ScopeDecision = { verdict: ScopeVerdict; reason: string };

/**
 * 全省庁統一資格で参加できる案件かを判定する。
 *
 * 対象外の理由は必ず残す。あとから「なぜ解析されなかったのか」を説明できないと、
 * 取りこぼしに気づけない。
 */
export function judgeQualificationScope(input: ScopeInput): ScopeDecision {
  // 建設工事は資格制度そのものが別（CLAUDE.md「やらないこと」）
  if (input.procurement === "工事") return { verdict: "対象外", reason: "建設工事（V2）" };

  switch (input.govScope) {
    case "自治体":
      return { verdict: "対象外", reason: "自治体（V2）" };
    case "独立行政法人等":
      // 統一資格をそのまま使わない法人が多い。件数が多いようなら方針を見直す
      return { verdict: "対象外", reason: "独立行政法人等（統一資格の範囲外）" };
    case "国":
      // 種別が取れていなくても、国の機関の工事以外は統一資格の範囲に入る
      return { verdict: "対象", reason: input.procurement === "不明" ? "国の機関（種別は不明）" : `国の機関（${input.procurement}）` };
    case "不明":
      return { verdict: "未判定", reason: "発注機関を分類できない" };
  }
}

/** 解析にお金をかけてよいか。未判定は解析しない（推測で費用を払わない）。 */
export function shouldAnalyze(decision: ScopeDecision): boolean {
  return decision.verdict === "対象";
}
