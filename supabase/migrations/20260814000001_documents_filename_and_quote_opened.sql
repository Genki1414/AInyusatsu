-- 1) 資料の元のファイル名を保持する。
-- 協力会社へ資料を送るとき、これまでは種別（kind）だけをファイル名にしていたため、
-- 種別の判定に失敗した資料が「その他」「その他_2」と並んで中身が分からなかった（実機で確認）。
-- 収集時に元のファイル名（例：06_数量総括表.pdf）を残し、送付時の表示名に使う。
alter table tender_documents add column filename text;

-- 2) 協力会社が回答ページ（/q/[token]）を開いた日時。
-- 「メールは届いたが見てもらえていない」のか「見たうえで回答が無い」のかを、
-- 依頼元が見積状況タブで区別できるようにする（初回の開封のみ記録する）。
alter table quotes add column opened_at timestamptz;
