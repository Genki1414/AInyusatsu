-- 発注機関が全省庁統一資格の範囲かどうかを持たせる。
-- 参照：CLAUDE.md「全省庁統一資格で参加できる入札案件を収集・解析し」
--       CLAUDE.md「やらないこと：自治体・建設工事（V2）」
--
-- 【なぜ必要か】
-- KKJ（官公需情報ポータル）は国の機関も自治体も区別せずに返す。
-- 実測（2026-08-21の公告日ぶん）では1日543件が入り、その25%が建設工事だった。
-- 全件をAI解析すると月100万円を超える（実測 約69円/件）。
--
-- kkj_sync は見つけた機関をすべて category='発注機関' で登録しており、
-- 国か自治体かを区別する列が無かった。そのため「対象外と決めてある案件」を
-- 解析から外すことができない。
--
-- 【なぜ機関側に持つか】
-- 案件は全ユーザー共通の1レコード（CLAUDE.md 最重要の前提1）で、1機関に多数ぶら下がる。
-- 案件ごとに判定すると同じ機関名を何度も判定することになり、直したいときも案件全部を
-- 触ることになる。機関に持たせれば1行直せば全案件に効く。
--
-- 【不明を残す】
-- 名前から判定できない機関は '不明' のままにする。推測で '国' にすると費用がかかり、
-- 推測で '自治体' にすると商機を落とす。どちらも黙って決めない。

alter table agencies add column gov_scope text;
  -- 国 / 自治体 / 独立行政法人等 / 不明。判定は packages/domain/src/qualification_scope.ts

create index agencies_gov_scope_idx on agencies (gov_scope);

comment on column agencies.gov_scope is
  '全省庁統一資格の範囲かを判断するための発注者区分（国 / 自治体 / 独立行政法人等 / 不明）。null は未分類';
